export function getCleanLocalityName(name: string): string {
  return name.replace(/\s*\([A-Z]+\)$/, "");
}

// Deterministic 0..1 position from a string (small hash) — used to spread
// commune labels inside the county bounding box when we don't have real coords.
export function deterministicHash01(str: string, salt = 0): number {
  let h = salt;
  for (let i = 0; i < str.length; i++) {
    h = (h * 31 + str.charCodeAt(i)) >>> 0;
  }
  return (h % 1000) / 1000;
}
